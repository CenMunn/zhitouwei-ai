export function findStock(keyword: string): StockProfile | null {
  const k = keyword.trim().toLowerCase()
  if (!k) return null
  return (
    STOCKS.find((s) => s.code === k) ??
    STOCKS.find((s) => s.name.toLowerCase() === k) ??
    STOCKS.find((s) => s.alias.some((a) => a.toLowerCase() === k)) ??
    STOCKS.find((s) => s.name.toLowerCase().includes(k) || k.includes(s.name.toLowerCase())) ??
    STOCKS.find((s) => s.alias.some((a) => a.length >= 2 && (k.includes(a.toLowerCase()) || a.toLowerCase().includes(k)))) ??
    null
  )
}

export interface SearchHit {
  code: string
  name: string
  industry: string
  market: string
  price: number
  currency: string
  changePct: number
}

export function searchStocks(q: string, limit = 8): SearchHit[] {
  const k = q.trim().toLowerCase()
  if (!k) return []
  const scored = STOCKS.map((s) => {
    let score = 0
    if (s.code === k) score = 100
    else if (s.name === q.trim()) score = 95
    else if (s.name.toLowerCase().startsWith(k)) score = 80
    else if (s.alias.some((a) => a.toLowerCase().startsWith(k))) score = 70
    else if (s.name.toLowerCase().includes(k)) score = 60
    else if (s.alias.some((a) => a.toLowerCase().includes(k))) score = 50
    else if (s.code.startsWith(k)) score = 45
    else if (s.industry.toLowerCase().includes(k)) score = 20
    return { s, score }
  })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
  return scored.map(({ s }) => ({ code: s.code, name: s.name, industry: s.industry, market: s.market, price: s.price, currency: s.currency, changePct: s.changePct }))
}
