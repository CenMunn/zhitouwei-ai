/** 展开后的全量词条 */
export const SLANG_TERMS: SlangEntry[] = Object.entries(D).flatMap(([cat, rows]) =>
  rows.map(([term, meaning, note]) => ({ term, meaning, cat, ...(note ? { note } : []) })),
)

/** 词典总条数（提示词/前端展示用） */
export const SLANG_TERMS_COUNT = SLANG_TERMS.length

/** 按词条长度降序（长词优先匹配，避免"打板"截断"打板族"类问题） */
const TERM_LIST: SlangEntry[] = [...SLANG_TERMS].sort((a, b) => b.term.length - a.term.length)

export interface SlangHit {
  term: string
  meaning: string
  cat: string
  note?: string
  pos: number
}

/**
 * 从文本中识别黑话术语（确定性，长词优先，位置排序）。
 * 用于：Agent 提示词注入（理解用户黑话提问）+ 前端翻译器高亮。
 */
export function matchSlang(text: string, opts?: { minLen?: number }): SlangHit[] {
  const minLen = opts?.minLen ?? 2
  const q = text.toLowerCase()
  const hits = new Map<string, SlangHit>()
  for (const entry of TERM_LIST) {
    if (entry.term.length < minLen) continue
    const idx = q.indexOf(entry.term.toLowerCase())
    if (idx === -1) continue
    // 同一位置长词优先：短词若被长词覆盖则跳过
    const covered = [...hits.values()].some((h) => idx >= h.pos && idx < h.pos + h.term.length)
    if (covered) continue
    // 更长的词覆盖之前的短词
    for (const [k, h] of hits) {
      if (h.pos >= idx && h.pos < idx + entry.term.length) hits.delete(k)
    }
    hits.set(entry.term, { term: entry.term, meaning: entry.meaning, cat: entry.cat, note: entry.note, pos: idx })
  }
  return [...hits.values()].sort((a, b) => a.pos - b.pos)
}

export interface SlangSegment {
  text: string
  hit?: SlangHit
}

/** 文本 → 高亮分段（黑话命中段带 hit，用于前端渲染翻译视图） */
export function segmentBySlang(text: string): SlangSegment[] {
  const hits = matchSlang(text)
  if (hits.length === 0) return [{ text }]
  const segs: SlangSegment[] = []
  let cur = 0
  for (const h of hits) {
    if (h.pos > cur) segs.push({ text: text.slice(cur, h.pos) })
    segs.push({ text: text.slice(h.pos, h.pos + h.term.length), hit: h })
    cur = h.pos + h.term.length
  }
  if (cur < text.length) segs.push({ text: text.slice(cur) })
  return segs
}

/** 词典内检索（分类过滤 + 关键词搜索，供前端词典浏览器使用） */
export function searchSlang(q: string, cat: string | null): SlangEntry[] {
  const kw = q.trim().toLowerCase()
  return SLANG_TERMS.filter((t) => {
    if (cat && t.cat !== cat) return false
    if (!kw) return true
    return t.term.toLowerCase().includes(kw) || t.meaning.toLowerCase().includes(kw)
  })
}

/** 黑话注释 → Agent 提示词块（无命中返回 null） */
export function slangBlockForPrompt(text: string): string | null {
  const hits = matchSlang(text)
  if (hits.length === 0) return null
  const lines = hits
    .slice(0, 10)
    .map((h) => `- 「${h.term}」：${h.meaning}${h.note ? `（注意：${h.note}，不作为事实依据）` : ''}`)
  return `用户提问中包含市场黑话/行话，必须按以下市场惯用含义理解（黑话只是描述性语言，不是交易信号，不得作为事实或预测依据）：\n${lines.join('\n')}`
}
